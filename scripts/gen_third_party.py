#!/usr/bin/env python3
"""Generates third-party/generated/deps.bzl from the installed fbthrift.

Kiln uses the folly, fbthrift, glog and gflags that Velox's setup scripts
install under /usr/local, and the system gtest. Rather than re-describing
their dependency graph in Buck, we configure scripts/deps_probe with CMake and
hand the compile flags and link lines CMake computed to Buck as
prebuilt_cxx_library flags. Re-run after reinstalling folly or fbthrift.

Usage: scripts/gen_third_party.py [--build-dir DIR]
"""

import argparse
import json
import os
import shlex
import shutil
import subprocess

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")

# Velox's setup scripts build folly and fbthrift with these machine flags.
# Code that inlines folly headers (F14 maps, SIMD helpers, ...) must match.
MACHINE_FLAGS = ["-mavx2", "-mfma", "-mavx", "-mf16c", "-mlzcnt", "-mbmi2"]


def link_libraries(build_ninja, target):
    with open(build_ninja) as f:
        found = False
        for line in f:
            if line.startswith(f"build {target}:"):
                found = True
            elif found and line.strip().startswith("LINK_LIBRARIES"):
                return shlex.split(line.split("=", 1)[1])
    raise SystemExit(f"link line for {target} not found in {build_ninja}")


def absolutize(build_dir, item):
    if item.startswith("-") or os.path.isabs(item):
        return item
    return os.path.normpath(os.path.join(build_dir, item))


def compile_flags(build_dir, target):
    """Defines (including the release build's -DNDEBUG, which folly was
    built with) and include paths of the probe's 'target' executable."""
    with open(os.path.join(build_dir, "compile_commands.json")) as f:
        commands = json.load(f)
    for entry in commands:
        if f"/{target}.dir/" in entry["output"]:
            args = shlex.split(entry["command"])[1:]
            break
    else:
        raise SystemExit(f"{target} not in compile_commands.json")

    flags = []
    it = iter(args)
    for arg in it:
        if arg in ("-isystem", "-I"):
            flags += [arg, next(it)]
        elif arg.startswith(("-D", "-I")):
            flags.append(arg)
    return flags


def unique(items):
    seen = set()
    return [x for x in items if not (x in seen or seen.add(x))]


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--build-dir", default=os.path.join(ROOT, "buck-out", "deps_probe"))
    args = parser.parse_args()
    build_dir = os.path.realpath(args.build_dir)

    subprocess.run(
        ["cmake", "-S", os.path.join(ROOT, "scripts", "deps_probe"),
         "-B", build_dir, "-GNinja", "-Wno-dev", "-DCMAKE_BUILD_TYPE=Release"],
        check=True, stdout=subprocess.DEVNULL)
    build_ninja = os.path.join(build_dir, "build.ninja")

    def libs(target):
        return unique([absolutize(build_dir, x)
                       for x in link_libraries(build_ninja, target)])

    def group(items):
        # One link group: the static folly/fbthrift archives in CMake's order
        # still have circular references.
        return ["-Wl,--start-group"] + items + ["-Wl,--end-group"]

    thrift1 = shutil.which("thrift1")
    if thrift1 is None:
        raise SystemExit("thrift1 (fbthrift's compiler) not on PATH")

    out_dir = os.path.join(ROOT, "third-party", "generated")
    os.makedirs(out_dir, exist_ok=True)
    out = os.path.join(out_dir, "deps.bzl")
    with open(out, "w") as f:
        f.write("# Generated by scripts/gen_third_party.py. Do not edit.\n\n")
        for name, value in [
            ("PREPROCESSOR_FLAGS",
             compile_flags(build_dir, "fbthrift_probe") + MACHINE_FLAGS),
            ("LINKER_FLAGS", group(libs("fbthrift_probe"))),
            ("GTEST_PREPROCESSOR_FLAGS", compile_flags(build_dir, "gtest_probe")),
            ("GTEST_LINKER_FLAGS", libs("gtest_probe")),
            ("THRIFT1", thrift1),
        ]:
            f.write(f"{name} = {json.dumps(value, indent=4)}\n\n")
    print(f"wrote {os.path.normpath(out)}")


if __name__ == "__main__":
    main()
